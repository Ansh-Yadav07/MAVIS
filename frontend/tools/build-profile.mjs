// Regenerates src/data/dataset-profile.js from reports/raw_data_profile.json.
// Run from the repo root:  node frontend/tools/build-profile.mjs
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const src = resolve(here, '../../reports/raw_data_profile.json');
const out = resolve(here, '../src/data/dataset-profile.js');
const raw = JSON.parse(readFileSync(src, 'utf8'));

// The CSV export of CIC-IDS2017 contains a mis-encoded dash in web attack labels.
const fixLabel = (l) => l.replace(/�/g, '–');

const files = raw.files.map((f) => ({
  source: f.source,
  dataset: f.source.startsWith('UNSW') ? 'UNSW-NB15' : 'CIC-IDS2017',
  format: f.format,
  rows: f.rows,
  columns: f.columns.length,
  target: f.target,
  fileSizeBytes: f.file_size_bytes,
  numericColumns: f.numeric_columns.length,
  categoricalColumns: f.categorical_columns,
  targetCounts: Object.fromEntries(Object.entries(f.target_counts).map(([k, v]) => [fixLabel(k), v])),
  missingValues: f.missing_values,
  infiniteValues: f.infinite_values,
  duplicateRows: f.within_source_duplicate_rows,
  rowsSeenEarlier: f.rows_seen_in_an_earlier_source,
  constantColumns: f.constant_columns,
}));

const cic = raw.files.find((f) => f.source.includes('pcap_ISCX'));
const profile = {
  generatedFrom: 'reports/raw_data_profile.json',
  scope: raw.scope,
  notes: raw.notes,
  cicColumns: cic.columns,
  files,
};

writeFileSync(out,
`// GENERATED by frontend/tools/build-profile.mjs from ${profile.generatedFrom}. Do not edit by hand.
// These are real values measured from the raw dataset files. No model output is included.
export const datasetProfile = ${JSON.stringify(profile, null, 2)};
`);
console.log('wrote', out);
